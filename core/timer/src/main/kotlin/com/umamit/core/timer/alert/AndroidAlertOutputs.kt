/*
 * Thin Android adapters for RingerModeAlertPlayer (04 §9.1). They hold no
 * decisions; the matrix and the repeats live in the player.
 */

/** Builds the ringer-mode [AlertPlayer] for the timer service. */
object AlertPlayers {
    fun ringerMode(context: Context, settings: () -> AlertSettings = { AlertSettings() }): AlertPlayer {
        val appContext = context.applicationContext
        return RingerModeAlertPlayer(
            environment = AndroidAlertEnvironment(appContext),
            sound = MediaPlayerSoundOutput(appContext),
            haptics = VibratorHaptics(appContext),
            scheduler = HandlerAlertScheduler(),
            settings = settings,
        )
    }
}

/** The `res/raw` file of each [AlertSound] (generated by `scripts/sounds/generate.sh`). */
@get:RawRes
val AlertSound.rawRes: Int
    get() = when (this) {
        AlertSound.KLANGSCHALE -> ContentR.raw.klangschale
        AlertSound.TICK -> ContentR.raw.tick
    }

/** Ringer mode from [AudioManager], calls from the audio mode, DND from the interruption filter. */
internal class AndroidAlertEnvironment(context: Context) : AlertEnvironment {
    private val audioManager = context.getSystemService(AudioManager::class.java)
    private val notificationManager = context.getSystemService(NotificationManager::class.java)

    override fun conditions(): AlertConditions {
        val ringerMode = when (audioManager?.ringerMode) {
            AudioManager.RINGER_MODE_NORMAL -> RingerMode.NORMAL

            AudioManager.RINGER_MODE_SILENT -> RingerMode.SILENT

            // RINGER_MODE_VIBRATE; also without an AudioManager (never on a phone),
            // where vibrating beats silence.
            else -> RingerMode.VIBRATE
        }
        val filter = notificationManager?.currentInterruptionFilter
        return AlertConditions(
            ringerMode = ringerMode,
            inCall = audioManager?.mode in CALL_MODES,
            dndBlocksAlerts = filter == NotificationManager.INTERRUPTION_FILTER_NONE ||
                filter == NotificationManager.INTERRUPTION_FILTER_ALARMS,
        )
    }

    private companion object {
        /** Ringing, in a call, in a VoIP call, call screening or redirected calls. */
        val CALL_MODES = setOf(
            AudioManager.MODE_RINGTONE,
            AudioManager.MODE_IN_CALL,
            AudioManager.MODE_IN_COMMUNICATION,
            AudioManager.MODE_CALL_SCREENING,
            AudioManager.MODE_CALL_REDIRECT,
            AudioManager.MODE_COMMUNICATION_REDIRECT,
        )
    }
}

/**
 * Plays with `USAGE_NOTIFICATION_EVENT` (notification volume, subject to Do
 * Not Disturb) and transient audio focus with ducking. One [MediaPlayer] per
 * play, released on completion, error or [stop]. Failures are logged and
 * never thrown: the vibration and the visual alert must still happen.
 */
internal class MediaPlayerSoundOutput(private val context: Context) : AlertSoundOutput {
    private val audioManager = context.getSystemService(AudioManager::class.java)
    private val handler = Handler(Looper.getMainLooper())
    private var player: MediaPlayer? = null
    private var focusRequest: AudioFocusRequest? = null

    /** For tests: a sound is playing right now. */
    internal val isPlaying: Boolean
        get() = player?.isPlaying == true

    override fun requestFocus(onLost: () -> Unit): Boolean {
        val manager = audioManager ?: return false
        val request = AudioFocusRequest.Builder(AudioManager.AUDIOFOCUS_GAIN_TRANSIENT_MAY_DUCK)
            .setAudioAttributes(ATTRIBUTES)
            .setOnAudioFocusChangeListener(
                { change ->
                    // The system ducks us for CAN_DUCK; a real loss ends the sound.
                    if (change == AudioManager.AUDIOFOCUS_LOSS || change == AudioManager.AUDIOFOCUS_LOSS_TRANSIENT) {
                        Log.i(TAG, "Audio focus lost ($change)")
                        onLost()
                    }
                },
                handler,
            )
            .build()
        val granted = manager.requestAudioFocus(request) == AudioManager.AUDIOFOCUS_REQUEST_GRANTED
        if (granted) focusRequest = request else Log.i(TAG, "Audio focus refused")
        return granted
    }

    override fun abandonFocus() {
        val request = focusRequest ?: return
        focusRequest = null
        audioManager?.abandonAudioFocusRequest(request)
    }

    override fun play(sound: AlertSound) {
        stop()
        val sessionId = audioManager?.generateAudioSessionId() ?: AudioManager.AUDIO_SESSION_ID_GENERATE
        // create() prepares synchronously and returns null on failure.
        val created = MediaPlayer.create(context, sound.rawRes, ATTRIBUTES, sessionId)
        if (created == null) {
            Log.w(TAG, "Cannot play $sound")
            return
        }
        created.setOnCompletionListener { release(it) }
        created.setOnErrorListener { mp, what, extra ->
            Log.w(TAG, "Playback error $what/$extra for $sound")
            release(mp)
            true
        }
        player = created
        try {
            created.start()
        } catch (e: IllegalStateException) {
            Log.w(TAG, "Cannot start $sound", e)
            release(created)
        }
    }

    override fun stop() {
        player?.let { release(it) }
    }

    private fun release(mediaPlayer: MediaPlayer) {
        if (player === mediaPlayer) player = null
        try {
            if (mediaPlayer.isPlaying) mediaPlayer.stop()
        } catch (e: IllegalStateException) {
            Log.w(TAG, "Stop failed", e)
        }
        mediaPlayer.release()
    }

    companion object {
        /** 04 §9.1: notification-event usage (notification volume, DND respected). */
        val ATTRIBUTES: AudioAttributes = AudioAttributes.Builder()
            .setUsage(AudioAttributes.USAGE_NOTIFICATION_EVENT)
            .setContentType(AudioAttributes.CONTENT_TYPE_SONIFICATION)
            .build()
    }
}

/** Vibrates through the default vibrator with `VibrationAttributes.USAGE_NOTIFICATION` (04 §9.1). */
internal class VibratorHaptics(context: Context) : AlertHaptics {
    private val vibrator: Vibrator? = context.getSystemService(VibratorManager::class.java)?.defaultVibrator

    @RequiresPermission(Manifest.permission.VIBRATE)
    override fun play(haptic: Haptic) {
        val target = vibrator?.takeIf { it.hasVibrator() } ?: return
        target.vibrate(VibrationEffect.createWaveform(haptic.timings.toLongArray(), NO_REPEAT), ATTRIBUTES)
    }

    @RequiresPermission(Manifest.permission.VIBRATE)
    override fun cancel() {
        vibrator?.cancel()
    }

    companion object {
        private const val NO_REPEAT = -1
        val ATTRIBUTES: VibrationAttributes = VibrationAttributes.createForUsage(VibrationAttributes.USAGE_NOTIFICATION)
    }
}

/** Runs the player's delayed actions on the main thread with its own [Handler]. */
internal class HandlerAlertScheduler(private val handler: Handler = Handler(Looper.getMainLooper())) : AlertScheduler {
    override fun schedule(delayMs: Long, action: () -> Unit) {
        handler.postDelayed({ action() }, delayMs)
    }

    override fun cancelAll() {
        handler.removeCallbacksAndMessages(null)
    }
}

